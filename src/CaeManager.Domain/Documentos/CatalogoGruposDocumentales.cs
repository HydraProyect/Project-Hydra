    public static IReadOnlyList<(AmbitoAplicacion Ambito, string Grupo)> Grupos { get; } = Entradas.Select(e => (e.Ambito, e.Grupo)).Distinct().ToArray();

    public static string Grupo(AmbitoAplicacion ambito, string nombre) => Buscar(ambito, nombre)?.Grupo ?? "Sin grupo";
    public static bool EsArchivado(AmbitoAplicacion ambito, string nombre) => Buscar(ambito, nombre)?.Archivado ?? false;
    private static Entrada? Buscar(AmbitoAplicacion ambito, string nombre) => Entradas.FirstOrDefault(e =>
        e.Ambito == (ambito == AmbitoAplicacion.Cliente ? AmbitoAplicacion.Empresa : ambito) && string.Equals(e.Nombre, nombre.Trim(), StringComparison.OrdinalIgnoreCase));
